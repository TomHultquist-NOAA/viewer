'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {SurfaceWeatherOverlay}=require('../js/surface-weather-overlay.js');
const events=new Map();
const ctx={canvas:null,setTransform(){},clearRect(){},beginPath(){},moveTo(){},lineTo(){},stroke(){},fill(){},closePath(){},setLineDash(){},strokeText(){},fillText(){}};
const mapHost={style:{},appendChild(){},getBoundingClientRect:()=>({width:800,height:500})};
global.getComputedStyle=()=>({position:'relative'});
global.document={createElement:(type)=>type==='canvas'?{style:{},clientWidth:800,clientHeight:500,getContext(){return ctx},remove(){}}:{style:{},appendChild(){}},createTextNode:()=>({})};
global.requestAnimationFrame=cb=>{cb();return 1};

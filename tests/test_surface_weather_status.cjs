const pt=(type='low')=>({type:'Feature',properties:{type,pressure_hpa:1000,confidence:.9},geometry:{type:'Point',coordinates:[-100,39]}});
const line=(type='cold_front')=>({type:'Feature',properties:{type,confidence:.9},geometry:{type:'LineString',coordinates:[[-104,40],[-100,39]]}});
const fc=features=>({type:'FeatureCollection',features});
(async()=>{
 const statuses=[],o=new SurfaceWeatherOverlay(map,{baseUrl:'data/surface_weather',onStatusChange:s=>statuses.push(s)});
 global.fetch=async()=>({ok:true,json:async()=>fc([pt(),line()])});
 assert.equal(await o.setFrame('rrfs','20261114','12',1),true);
 assert.equal(o.status.state,'ready');assert.equal(o.status.count,2);assert.equal(o.status.selectedCount,2);
 assert.ok(statuses.some(s=>s.state==='loading'));
 o.setSettings({centers:false,fronts:false,troughs:false,drylines:false});
 assert.equal(o.status.state,'filtered','valid overlay file but selected types are off');
 o.setSettings({centers:true});assert.equal(o.status.state,'ready');assert.equal(o.status.selectedCount,1);
 global.fetch=async()=>({ok:true,json:async()=>({...fc([]),metadata:{missing_inputs:['dpt2m']}})});
 await o.setFrame('rrfs','20261114','12',2);
 assert.equal(o.status.state,'empty','published but genuinely empty file');
 assert.match(o.status.detail,/dpt2m/);
 let requests=0;
 global.fetch=async()=>{requests++;return {ok:false,status:404}};
 await o.setFrame('rrfs','20261114','12',3);
 assert.equal(o.status.state,'missing','404 means frame was not published');
 assert.equal(o.status.count,0);
 await o.setFrame('rrfs','20261114','12',3);
 assert.equal(requests,1,'negative cache should reduce repeated 404s');
 global.fetch=async()=>({ok:false,status:503});
 await o.setFrame('rrfs','20261114','12',4);
 assert.equal(o.status.state,'error','server problem must not be mislabelled as empty');
 await o.setFrame('rrfs','20261114','12',3);
 assert.equal(o.status.state,'missing','negative cache preserves original error classification');
 global.fetch=async()=>({ok:true,json:async()=>({type:'notGeoJSON',features:[]})});
 await o.setFrame('rrfs','20261114','12',5);
 assert.equal(o.status.state,'error','malformed JSON must not be labelled as no features');
 global.fetch=async()=>({ok:true,json:async()=>{throw new SyntaxError('Unexpected token <')}});
 await o.setFrame('rrfs','20261114','12',6);
 assert.equal(o.status.state,'error');
 assert.match(o.status.detail,/Invalid GeoJSON response/,'HTML server error response must be diagnosed separately');
 global.fetch=async()=>({ok:false,status:403});
 await o.setFrame('rrfs','20261114','12',7);
 assert.equal(o.status.state,'error');
 assert.match(o.status.detail,/HTTP 403/);
 o.clear();assert.equal(o.status.state,'idle');
 o.dispose();assert.equal(events.size,0);
 // Verify the actual viewer controls and per-panel message orchestration.
 const viewer=fs.readFileSync(path.join(__dirname,'../js/viewer.js'),'utf8');
 const start=viewer.indexOf('function surfaceWeatherEligible(){'),stop=viewer.indexOf('function createMap(p){',start);
 assert.ok(start>0&&stop>start);
 const output={hidden:false,textContent:''},retry={hidden:true},note={hidden:true,dataset:{},textContent:'',title:''};
 const state={field:'mslp',surfaceWeatherEnabled:true,surfaceWeatherSettings:{centers:true},panels:[]};
 const elements={surfaceWeatherStatus:output,surfaceWeatherRetryBtn:retry};
 const sandbox={st:state,el:elements,SURFACE_MSLP_IMAGE_FIELDS:new Set(['t2m']),Date,Promise,Number,String};
 vm.createContext(sandbox);vm.runInContext(viewer.slice(start,stop),sandbox);
 const panel={map:{},cfg:{differencePanel:false},surfaceWeatherNotice:note};state.panels.push(panel);
 sandbox.updateSurfaceWeatherPanelStatus(panel,{state:'loading'});
 assert.match(output.textContent,/1 loading/);assert.match(note.textContent,/Loading/);
 sandbox.updateSurfaceWeatherPanelStatus(panel,{state:'missing'});
 assert.match(output.textContent,/1 not published/);assert.equal(retry.hidden,false);assert.match(note.textContent,/Not published/);
 sandbox.updateSurfaceWeatherPanelStatus(panel,{state:'empty'});
 assert.match(output.textContent,/no detected features/);assert.match(note.textContent,/No features detected/);
 sandbox.updateSurfaceWeatherPanelStatus(panel,{state:'ready',count:2});
 assert.match(output.textContent,/1 with features/);assert.equal(note.hidden,true);assert.equal(retry.hidden,true);
 sandbox.updateSurfaceWeatherPanelStatus(panel,{state:'error',detail:'HTTP 403'});
 assert.match(note.textContent,/Access denied \(HTTP 403\)/);
 assert.match(output.textContent,/First error: HTTP 403/);
 sandbox.updateSurfaceWeatherPanelStatus(panel,{state:'error',detail:'Invalid GeoJSON response'});
 assert.match(note.textContent,/Invalid overlay response/);
 sandbox.updateSurfaceWeatherPanelStatus(panel,{state:'error',detail:'HTTP 503'});
 assert.match(note.textContent,/Server error \(HTTP 503\)/);
 sandbox.updateSurfaceWeatherPanelStatus(panel,{state:'error',detail:'HTTP 429'});
 assert.match(note.textContent,/Server busy \(HTTP 429\)/);
 state.surfaceWeatherEnabled=false;sandbox.updateSurfaceWeatherPanelStatus(panel,{state:'missing'});
 assert.equal(output.hidden,true);assert.equal(note.hidden,true);
 const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
 assert.match(html,/id="surfaceWeatherStatus"/);assert.match(html,/id="surfaceWeatherRetryBtn"/);
 assert.doesNotMatch(html,/id="surfaceWeatherToggleBtn" checked/, 'master overlay should be unchecked in HTML');
 assert.match(viewer,/const st=\{surfaceWeatherEnabled:false/,'initial JS default should be OFF');
 const style=fs.readFileSync(path.join(__dirname,'../css/styles.css'),'utf8');
 assert.match(style,/\.surface-weather-panel-status\{position:absolute;right:8px;bottom:46px;/,'status should clear the lower-right fullscreen button');
 assert.match(style,/\.surface-weather-panel-status\{right:6px;bottom:44px;/,'mobile status should clear fullscreen too');
 // Regression: first load of v1.2.92 turns off the old auto-enabled flag;
 // user can then explicitly turn it ON and the choice persists on later visits.
 const preferenceStart=viewer.indexOf(' // v1.2.92: Surface weather must start OFF.');
 const preferenceEnd=viewer.indexOf(' for(const [id,key]',preferenceStart);
 assert.ok(preferenceStart>0&&preferenceEnd>preferenceStart);
 const savedPrefs=new Map([['omd_evu_surface_weather_enabled','1']]);
 const storage={getItem:key=>savedPrefs.get(key)??null,setItem:(key,value)=>savedPrefs.set(key,value)};
 const prefsState={surfaceWeatherEnabled:true,surfaceWeatherSettings:{centers:true}};
 const prefCtx={st:prefsState,localStorage:storage,JSON,Object};
 vm.createContext(prefCtx);
 vm.runInContext(viewer.slice(preferenceStart,preferenceEnd),prefCtx);
 assert.equal(prefsState.surfaceWeatherEnabled,false,'old automatically-on state must be migrated OFF');
 assert.equal(savedPrefs.get('omd_evu_surface_weather_enabled'),'0');
 assert.equal(savedPrefs.get('omd_evu_surface_weather_default_off_v1292'),'1');
 savedPrefs.set('omd_evu_surface_weather_enabled','1');
 vm.runInContext(viewer.slice(preferenceStart,preferenceEnd),prefCtx);
 assert.equal(prefsState.surfaceWeatherEnabled,true,'explicit new ON preference should survive reload');
 console.log('PASS: surface weather status, HTTP diagnosis, overlay default OFF and one-time saved-preference migration, fullscreen clearance');
})().catch(e=>{console.error(e);process.exitCode=1});

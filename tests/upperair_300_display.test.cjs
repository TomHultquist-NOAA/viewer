'use strict';
const assert=require('node:assert/strict'),fs=require('fs'),path=require('path'),vm=require('node:vm');
const source=fs.readFileSync(path.join(__dirname,'../js/viewer.js'),'utf8');
const context=vm.createContext({});vm.runInContext(source.slice(0,source.indexOf('const PTYPE_LABELS=')),context);
const v=(x)=>vm.runInContext(x,context);
assert.equal(v('FIELDS.wspd300.convert'),'mpsToKt');
assert.equal(v('FIELDS.wspd300.unit'),'kt');
assert.equal(v("FIELD_MENU_GROUPS.find(x=>x.key==='upperair').fields.some(x=>x.key==='wspd300')"),true);
assert.match(source,/field==='wspd300'\?300/);
assert.match(source,/field==='wspd300'\?'h300'/);
assert.match(source,/h300:\[120,120,120\]/);
assert.match(source,/overlayMSLP:true/);
assert.match(source,/omd_evu_mslp_isobars/);
assert.match(source,/heightContour\|\|isobarContour/);
assert.equal(v('FIELDS.sbcape.cutoff'),10);
assert.equal(v('FIELDS.mucape.cutoff'),10);
assert.equal(v('FIELDS.mxuphl.bandColors.includes("#00000000")'),true);
assert.equal(v('FIELDS.mxuphl_run.bandColors.includes("#00000000")'),true);
console.log('PASS 300-hPa wind display, height/wind overlays, MSLP visibility, contours and zero-transparent CAPE/UH');

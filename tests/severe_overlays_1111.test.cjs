'use strict';
const fs=require('fs'),vm=require('vm'),assert=require('assert');
const code=fs.readFileSync(require('path').join(__dirname,'../js/viewer.js'),'utf8');
const start=code.indexOf('function shearOverlayScale('),end=code.indexOf('async function prepareWindBarbs(',start);
const ctx=vm.createContext({console,Float32Array,Number,Math});
vm.runInContext(code.slice(start,end),ctx);
const gradU=Float32Array.from({length:400},()=>.003);
const gradV=Float32Array.from({length:400},()=>.004);
assert.equal(vm.runInContext('shearOverlayScale(gradU,gradV,6000)',Object.assign(ctx,{gradU,gradV})),6000);
const speedU=Float32Array.from({length:400},()=>18);
const speedV=Float32Array.from({length:400},()=>24);
assert.equal(vm.runInContext('shearOverlayScale(speedU,speedV,6000)',Object.assign(ctx,{speedU,speedV})),1);
assert.equal(vm.runInContext('shearOverlayScale(gradU,gradV,1000)',ctx),1000);
assert.equal(vm.runInContext('shearOverlayScale(ambiguous,speedV.map(()=>0),6000)',Object.assign(ctx,{ambiguous:Float32Array.from({length:400},()=>.08)})),null);
const fields=code.slice(code.indexOf('function windComponentNames('),code.indexOf('// Secondary MSLP overlay:',code.indexOf('function windComponentNames(')));
const lookup=vm.createContext({heightVariableName:()=>null});
vm.runInContext(fields,lookup);
assert.equal(lookup.windComponentNames('shear06').join(','),'shru06,shrv06');
assert.equal(lookup.windComponentNames('srh03').join(','),'ustm,vstm');
assert.equal(lookup.windComponentNames('srh01').join(','),'ustm,vstm');
assert.doesNotMatch(code,/paintShearArrow/);
assert.match(code,/paintBarb\(ctx,x,y,dx,dy,speed,size\)/);
assert.match(code,/st\.field\.startsWith\('shear'\)\?'Shear barbs'/);
assert.match(code,/\{convert:null\}/);
assert.match(code,/overlaySevereWind:true/);
console.log('PASS bulk-shear normalization, right-mover overlay wiring, native wind-component ingestion');

'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.join(__dirname,'..');
const src=fs.readFileSync(path.join(root,'js/viewer.js'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const css=fs.readFileSync(path.join(root,'css/styles.css'),'utf8');
const ctx=vm.createContext({});
vm.runInContext(src.slice(0,src.indexOf('const PTYPE_LABELS=')),ctx);
const groups=Array.from(vm.runInContext('FIELD_MENU_GROUPS',ctx),g=>({key:g.key,fields:Array.from(g.fields,f=>f.key)}));
assert.deepEqual(groups.map(g=>g.key),['radar','surface','precip','snow','upperair','shear','convective']);
const flat=groups.flatMap(g=>g.fields),all=Array.from(vm.runInContext('fieldMenuEntries()',ctx),f=>f.key);
assert.equal(flat.length,all.length);assert.equal(new Set(flat).size,all.length);
assert.deepEqual([...flat].sort(),[...all].sort());
for(const key of ['absv500','shear01','shear06','srh01','srh03','mxuphl','mxuphl_run','scp','stp','stp_fixed','snow48h','apcp48h'])assert(flat.includes(key));
assert.equal(groups.find(g=>g.key==='snow').fields.indexOf('asnow'),5);
assert.match(html,/id="fieldMenuBtn"[^>]*aria-haspopup="menu"/);
assert.match(html,/id="fieldMenuPopup"[^>]*hidden/);
assert.match(html,/id="fieldMenuCategories"/);assert.match(html,/id="fieldMenuBranch"/);
assert.match(html,/id="fieldMenuBack"/);assert.doesNotMatch(html,/id="fieldGroupSelect"|id="fieldSelect"/);
assert.match(html,/id="copyLinkBtn"[^>]*aria-label="Copy share link"/);
assert.doesNotMatch(html,/>Copy link</);
assert.match(src,/initializeFieldMenu\(\)/);assert.match(src,/onFieldMenuKeydown/);
assert.match(src,/navigator\.clipboard\?\.writeText/);assert.match(src,/document\.execCommand\('copy'\)/);
assert.match(src,/fieldMenuUI\.open\|\|document\.activeElement===el\.fieldMenuBtn/);
assert.match(src,/chooseFieldMenuField\(group\.key,field\.key\)/);
assert.match(css,/position:fixed;z-index:10000/);assert.match(css,/\.field-menu-popup\.is-drilled/);
assert.match(css,/data-controls-position="left"/);
console.log('PASS: single nested field menu, all eight groups, field coverage, touch and keyboard hooks, share icon and sidebar-safe popup');

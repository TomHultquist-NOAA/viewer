'use strict';
const {readFileSync}=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const html=readFileSync(path.join(root,'index.html'),'utf8');
const css=readFileSync(path.join(root,'css/styles.css'),'utf8');
const js=readFileSync(path.join(root,'js/viewer.js'),'utf8');
const legend=html.match(/<section id="sharedLegend"[\s\S]*?<\/section>/)?.[0];
assert.ok(legend,'shared legend section');
const header=legend.match(/<div class="shared-legend-heading">([\s\S]*?)<\/div>\s*<\/div>/)?.[0];
assert.ok(header,'reset control and field title should share a heading row');
assert.match(header,/id="sharedLegendTitle"/);
assert.match(header,/id="legendResetBtn"/);
assert.match(header,/aria-label="Reset color scale to default"/);
assert.match(header,/<svg aria-hidden="true"/);
assert.doesNotMatch(header,/>Reset scale<\/button>/,'no full-width text button');
assert.ok(legend.indexOf('id="legendResetBtn"')<legend.indexOf('class="shared-legend-track"'));
assert.match(css,/\.shared-legend-heading\{display:grid;/);
assert.match(css,/\.legend-reset\{grid-column:3;grid-row:1;position:static;/);
assert.doesNotMatch(css,/\.legend-reset\{[^}]*position:absolute;/);
assert.match(css,/\.legend-reset:focus-visible/);
assert.match(js,/el\.legendResetBtn\.addEventListener\('click',\(\)=>\{\s*st\.colorRanges\.delete\(st\.field\);closeLegendRangeEditor\(\);refreshColorbarRange\(\);/);
assert.match(js,/el\.legendResetBtn\.hidden=!custom;/);
console.log('PASS icon reset occupies its own heading slot without obscuring colorbar; accessible behavior preserved');

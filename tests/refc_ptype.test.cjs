'use strict';
const assert=require('node:assert/strict'),vm=require('node:vm'),fs=require('node:fs'),path=require('node:path');
const src=fs.readFileSync(path.join(__dirname,'../js/viewer.js'),'utf8');
assert.match(src,/fields:\['refc','ptype','refc_ptype'/);
const fields=vm.createContext({});vm.runInContext(src.slice(0,src.indexOf('const PTYPE_LABELS=')),fields);
const menu=vm.runInContext('FIELD_MENU_GROUPS.find(g=>g.key==="radar").fields.map(f=>f.key)',fields);
assert.equal(Array.from(menu).indexOf('refc_ptype'),2);
const a=src.indexOf('const REFC_PTYPE_SHADES='),b=src.indexOf('function pal(m,v)',a);
assert(a>0&&b>a);
const context=vm.createContext({Float32Array,Math,Number,Error});
vm.runInContext(src.slice(a,b),context);
const out=vm.runInContext('blendReflectivityPtype(new Float32Array([8,12,45,80,25,20,30]),new Float32Array([1,1,2,3,4,0,2.2]))',context);
assert.equal(out[0],-1e10,'subthreshold reflectivity transparent');
assert.equal(out[1],12,'rain intensity');
assert.equal(out[2],125,'snow encoded independently');
assert.ok(Math.abs(out[3]-239.9)<1e-4,'freezing rain intensity capped inside bin');
assert.equal(out[4],265,'sleet intensity');
assert.equal(out[5],-1e10,'no ptype hidden');
assert.equal(out[6],-1e10,'fractional interpolated ptype rejected');
const palette=vm.runInContext('reflectivityPtypePalette()',context);
assert.equal(palette.levels.length,palette.colors.length+1);
assert.equal(palette.colors.filter(c=>c==='#00000000').length,4);
assert.ok(palette.colors.every(c=>/^#[0-9a-f]{6}(?:00)?$/.test(c)));
assert.match(src,/Ptype F\$\{pad3\(h\)\} unavailable/);
assert.match(src,/no matching analysis Ptype is available/);
console.log('PASS native reflectivity/Ptype palette, categorical isolation, and missing-data handling');
// Rain is green at low values, yellow at medium-high, orange at the top.
const colorAt=v=>vm.runInContext(`reflectivityPtypeColor(1,${v})`,context);
const rgb=hex=>[1,3,5].map(i=>parseInt(hex.slice(i,i+2),16));
const low=rgb(colorAt(20)),mid=rgb(colorAt(55)),hi=rgb(colorAt(70));
assert(low[1]>low[0],'low rain remains green');
assert(mid[0]>200&&mid[1]>150,'strong rain reaches yellow');
assert(hi[0]>hi[1]&&hi[1]>hi[2],'highest rain reaches orange');
assert(!palette.colors.some(c=>c.toLowerCase()==='#ff0000'),'rain palette contains no pure red');

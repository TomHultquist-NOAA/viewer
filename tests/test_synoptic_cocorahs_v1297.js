'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');const vm=require('node:vm');const path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../js/viewer.js'),'utf8');
const block=source.slice(source.indexOf('const AMOUNT_REPORT_EMPTY='),source.indexOf('function observationVisible(){'));
const st={field:'apcp24h',hour:24,ref:{id:'case'},amountReportEnabled:{metar:true,cocorahs:true}};
const ctx={st,Date,Number,console,devicePixelRatio:1};vm.createContext(ctx);vm.runInContext(block,ctx);
const daily=(end)=>({type:'Feature',geometry:{type:'Point',coordinates:[-77,39]},properties:{source:'cocorahs',station:'VA-LD-1',report_date:'2026-11-14',report_local_time:'07:00',time_basis:'single-zone-state',period_hours:24,end_utc:end,precip_in:1.25}});
let rows=[daily('2026-11-14T12:00:00Z')];
let f=ctx.amountReportSelection(rows,new Date('2026-11-14T12:00:00Z'),'apcp24h');
assert.equal(f.length,1,'CoCoRaHS 24h total must appear at a valid 12 UTC hour');
assert.equal(ctx.amountReportSelection(rows,new Date('2026-11-14T13:00:00Z'),'apcp24h').length,0,'report must not repeat at 13 UTC');
assert.equal(ctx.amountReportSelection(rows,new Date('2026-11-14T12:00:00Z'),'apcp1h').length,0,'24h total must not appear on 1h field');
const metar={type:'Feature',geometry:{type:'Point',coordinates:[-104,39]},properties:{source:'metar',station:'KDEN',provider:'Synoptic Data (ASOS/AWOS)',end_utc:'2026-11-14T12:00:00Z',period_hours:24,precip_in:.24,report_type:'derived precipitation'}};
f=ctx.amountReportSelection([metar],new Date('2026-11-14T12:00:00Z'),'apcp24h');
assert.equal(f.length,1);
assert.match(ctx.amountReportPopupText(f[0]),/Synoptic Data \(ASOS\/AWOS\)/);
assert.equal(ctx.amountReportLabel(f[0]),'0.24','numbers must not be prefixed by source');
console.log('PASS: CoCoRaHS local-to-UTC valid frame, strict period, Synoptic METAR source attribution');
